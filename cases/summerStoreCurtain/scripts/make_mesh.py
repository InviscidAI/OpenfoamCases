def is_air(a, b):
    if a < 0:
        return True
    if a < .15:
        return b < 2.13
    return b < 2.9 and not (a < .45 and 2.18 < b < 2.43)


def classify(a, b):
    """The patch of a boundary face whose centre is (a, b)."""
    e = 1e-9
    if abs(a + 5) < e:
        return 'street'
    if abs(b - 6) < e:
        return 'sky'
    if abs(b) < e:
        return 'sidewalk' if a < 0 else 'floor'
    if abs(a - 10.15) < e:
        return 'backWall'
    if abs(b - 2.18) < e and .16 < a < .22:
        return 'curtainSlot'
    if abs(a - .45) < e and 2.2 < b < 2.41:
        return 'curtainIntake'
    if .15 - e <= a <= .45 + e and 2.18 - e <= b <= 2.43 + e and not (abs(a - .15) < e and b > 2.18):
        return 'curtainBody'
    if abs(b - 2.9) < e and a > .15:
        return 'ceiling'
    if abs(a) < e and b > 2.13:
        return 'storefront'
    if abs(b - 2.13) < e and 0 < a < .15:
        return 'doorHead'
    if abs(a - .15) < e and b > 2.13:
        return 'frontInside'
    raise ValueError((a, b))


